const DICTIONARIES: Record<UiLang, Record<Key, string> | null> = {
  'pt-BR': null,
  en,
  es,
  fr,
  de,
  it,
  ja,
  zh,
};

/** English is the default, whatever the browser's language. */
export const DEFAULT_UI_LANG: UiLang = 'en';

let locale: UiLang = DEFAULT_UI_LANG;

export function getLocale(): UiLang {
  return locale;
}

/** Set from prefs.uiLang by each context that shows text (pages, background). */
export function setLocale(lang: UiLang): void {
  locale = lang;
}

function lookup(text: string): string | undefined {
  return DICTIONARIES[locale]?.[text as Key];
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = lookup(key) ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/**
 * Translates a message that arrived as text (errors from the background, the
 * offscreen document or a worker, which never load the locale). "Prefix: rest"
 * is translated on both sides; anything unknown is shown as it came.
 */
export function tr(message: string): string {
  const own = lookup(message);
  if (own) return own;
  const at = message.indexOf(': ');
  if (at < 0) return message;
  return `${tr(message.slice(0, at))}: ${tr(message.slice(at + 2))}`;
}

/**
 * Names the app gives documents (untitled, chapter N, page N) are stored in
 * Portuguese, so a library built under one language reads right in another.
 */
export function trName(name: string): string {
  if (name === 'Sem título') return t('Sem título');
  const chapter = /^Capítulo (\d+)$/.exec(name);
  if (chapter) return t('Capítulo {n}', { n: chapter[1]! });
  const page = /^Página (\d+)$/.exec(name);
  return page ? t('Página {n}', { n: page[1]! }) : name;
}

/**
 * Pages: load the locale before the first render, then reload when it changes,
 * which is simpler than re-rendering every translated string in place.
 */
export function startPageLocale(lang: UiLang): void {
  setLocale(lang);
  document.documentElement.lang = locale;
  chrome.storage.local.onChanged.addListener((changes) => {
    const next = (changes.prefs?.newValue as { uiLang?: UiLang } | undefined)?.uiLang;
    if (next && next !== locale) location.reload();
  });
}
